import {chromium} from 'playwright';
import fs from 'node:fs/promises';
await fs.mkdir('test-results',{recursive:true});
process.env.BLOSSOM_PORT='4174';
const {server}=await import('./serve.mjs');
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1600,height:900},deviceScaleFactor:1});
const page=await context.newPage();const errors=[];const failures=[];
page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)failures.push(r.url()+' '+r.status());});
await page.goto('http://127.0.0.1:4174');await page.waitForSelector('#stage.screen-home');await page.waitForTimeout(700);
await page.screenshot({path:'test-results/home.png'});
for(const name of ['modes','collection','formation','summon','sect','inventory']){
  await page.locator(`[data-action="navigate"][data-screen="${name}"]`).first().click();
  await page.waitForTimeout(120);await page.screenshot({path:`test-results/${name}.png`});
  await page.locator('[data-action="navigate"][data-screen="home"]').first().click();
}
await page.locator('[data-action="navigate"][data-screen="collection"]').first().click();
await page.locator('[data-action="hero"][data-id="ling_shuang"]').first().click();
await page.waitForTimeout(250);
await page.screenshot({path:'test-results/hero.png'});
await page.locator('[data-action="close"]').click();
await page.locator('[data-action="navigate"][data-screen="summon"]').first().click();
await page.locator('[data-action="summon"][data-count="10"]').click();
await page.waitForSelector('.summon-result');
await page.waitForTimeout(1300);
if(await page.locator('.summon-result').count()!==10)throw Error('Ten summon missing results');
await page.screenshot({path:'test-results/reveal.png'});
await page.locator('.modal-close').click();
await page.locator('[data-action="navigate"][data-screen="home"]').first().click();
await page.locator('[data-action="navigate"][data-screen="modes"]').first().click();
await page.locator('[data-action="mode"][data-id="hunt"]').click();
await page.locator('[data-action="battle-start"]').click();
await page.waitForSelector('.battle-board');
await page.screenshot({path:'test-results/battle.png'});
await page.locator('[data-action="speed"]').click();await page.locator('[data-action="speed"]').click();
await page.locator('[data-action="auto"]').click();
await page.waitForSelector('.result-modal',{timeout:90000});
await page.waitForTimeout(300);
await page.screenshot({path:'test-results/victory.png'});
const diagnostics=await page.evaluate(()=>window.blossomDiagnostics());
await browser.close();
server.close();
console.log(JSON.stringify({errors,failures,diagnostics},null,2));
if(errors.length||failures.length)process.exitCode=1;
